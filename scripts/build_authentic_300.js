function makeItem(character, pinyin, pinyinPlain, pinyinNumbered, meaning) {
  const pinyins = [];
  const add = (s) => {
    if (!s) return;
    String(s).split(/[\/,;]+/).map(x => x.trim()).filter(Boolean).forEach(p => {
      if (!pinyins.includes(p)) pinyins.push(p);
    });
  };
  add(pinyin);
  add(pinyinPlain);
  add(pinyinNumbered);

  return {
    character,
    pinyin: pinyins,
    displayPinyin: pinyin,
    meaning
  };
}

