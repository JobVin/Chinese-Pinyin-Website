function buildStrict300(pool, filename, offset) {
  const map = new Map();
  for (let i = offset; i < pool.length; i++) {
    const x = pool[i];
    const item = makeItem(x[0], x[1], x[2], x[3], x[4]);
    if (!map.has(item.character)) {
      map.set(item.character, item);
    }
    if (map.size === 300) break;
  }

  const list = Array.from(map.values());
  fs.writeFileSync(path.join(dataDir, filename), JSON.stringify(list, null, 2), 'utf8');
  console.log(`[PASS] ${filename} built with exactly ${list.length} authentic items.`);
}

